"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const {load}=require("./helpers/ts-loader-v404.cjs");
const {planBeautifulLyricsV455:plan,lyricWordFillV455:fill}=load("components/visualizer/beautifulLyricsV455");
const base={line:{text:"Eins zwei drei vier fünf",startMs:1000,endMs:3500}, synchronized:true,playing:true,reducedMotion:false};
assert.equal(plan(base).density,"normal");
assert.equal(plan({...base,line:{...base.line,text:Array(16).fill("Wort").join(" "),endMs:3600}}).density,"rapid");
const rapid=plan({...base,line:{...base.line,text:Array(16).fill("Wort").join(" "),endMs:3600}});
assert(rapid.motionScale<.5);assert(rapid.fontScale<1);
assert.equal(plan({...base,reducedMotion:true}).motionScale,0);
assert.equal(plan({...base,playing:false}).motionScale,0);
assert.equal(plan({...base,synchronized:false}).estimatedWordsPerSecond,0);
assert.equal(plan({...base,line:{...base.line,words:[{text:"Eins",startMs:1000},{text:"zwei",startMs:1500}]}}).verifiedWordTiming,true);
assert.equal(plan({...base,line:{...base.line,words:[{text:"Eins",startMs:2000},{text:"zwei",startMs:1500}]}}).verifiedWordTiming,false);
assert.equal(fill({progressMs:1500,startMs:1000,endMs:2000,reducedMotion:false}),.5);
assert.equal(fill({progressMs:999,startMs:1000,endMs:2000,reducedMotion:false}),0);
assert.equal(fill({progressMs:5000,startMs:1000,endMs:2000,reducedMotion:true}),1);
assert.equal(fill({progressMs:NaN,startMs:1000,endMs:2000,reducedMotion:false}),0);
const renderer=fs.readFileSync("components/KineticLyrics.tsx","utf8");
const css=fs.readFileSync("app/globals.css","utf8");
assert(renderer.includes("planBeautifulLyricsV455("));
assert(renderer.includes("v455.motionScale"));
assert(css.includes(".v455-rapid.active"));
assert(css.includes("prefers-reduced-motion:reduce"));
assert(/^0\.1\.0-v(?:45[5-9]|4[6-9]\d|[5-9]\d\d)$/.test(require("../package.json").version));
console.log("PASS V455: rapid-rap damping, long-line typography, valid timing, pause, reduced motion and render wiring");
