const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const source = fs.readFileSync(path.join(__dirname, "../components/visualizer/groundContactEngine.ts"), "utf8");
const js = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod={exports:{}};new Function("module","exports",js)(mod,mod.exports);
const {createFootContactTracker,updateGroundContact}=mod.exports;
const step=(state, p, dt=1/60)=>updateGroundContact(state,p,0,dt,0.5,1);
const stationary={x:0,y:0.01,z:0,speed:0,verticalSpeed:0};
let s=createFootContactTracker();
assert.equal(s.phase,"airborne");
for(let i=0;i<10;i++)step(s,stationary);
assert.equal(s.phase,"planted","stationary foot plants");
assert(s.confidence>0.6,"plant confidence rises");
const anchor=s.plantedX;
step(s,{...stationary,x:0.009,speed:0.2});
assert.equal(s.phase,"planted","minor drift does not unplant");
assert.equal(s.plantedX,anchor,"plant anchor stays fixed");
step(s,{...stationary,y:0.2,speed:2,verticalSpeed:2});
assert.equal(s.phase,"releasing","high lift releases foot");
for(let i=0;i<40;i++)step(s,{...stationary,y:0.2,speed:0.1});
assert.equal(s.phase,"airborne","release eventually clears");
for(let i=0;i<8;i++)step(s,{...stationary,x:0.3});
assert.equal(s.phase,"planted","new contact established");
assert.equal(s.plantedX,0.3,"new plant position captured");
step(s,{...stationary,speed:NaN,verticalSpeed:Infinity},NaN);
assert(Number.isFinite(s.confidence),"invalid input bounded");
s=createFootContactTracker();step(s,{...stationary,y:0.3});
assert.equal(s.phase,"airborne","high foot not planted");
assert(source.includes('exitHeight = enterHeight'),"hysteresis threshold implemented");
console.log("Footwork grounding: 9 regression checks passed");
