const {test,expect,openSettings}=require('./fixtures.cjs');
const PREFS='sonic-display-ui-preferences-v1',CREW='sonic-stage-crew-v4',GROUP='sonic-multi-avatar-stage-v326';
const panel=dialog=>dialog.getByRole('group',{name:'Sonic Stage Crew – Musik und gemeinsame Show',exact:true});
test('crew preferences persist and trio setup restores previous models and grouping',async({page})=>{
 test.setTimeout(120000);
 let box=panel(await openSettings(page,'avatar'));
 await box.getByLabel('Musiksteuerung für Sonic Stage Crew',{exact:true}).uncheck();
 await box.getByLabel('Eigene Reaktionen der Figuren',{exact:true}).uncheck();
 await box.getByRole('combobox',{name:'Gemeinsame Choreografie',exact:true}).selectOption('canon');
 box=panel(await openSettings(page,'avatar'));
 await expect(box.getByLabel('Musiksteuerung für Sonic Stage Crew',{exact:true})).not.toBeChecked();
 await expect(box.getByRole('combobox',{name:'Gemeinsame Choreografie',exact:true})).toHaveValue('canon');
 const before=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),PREFS);
 await box.getByRole('button',{name:'Trio auf der Bühne einrichten',exact:true}).click();
 await expect.poll(()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)).avatarModelId,PREFS)).toBe('sonic-neon-pulse');
 const group=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),GROUP);
 expect(group).toMatchObject({enabled:true,count:3,songSync:false});expect(group.modelIds.slice(0,3)).toEqual(['sonic-neon-pulse','sonic-festival-nova','sonic-chrome-beat']);
 await expect(box.getByLabel('Musiksteuerung für Sonic Stage Crew',{exact:true})).toBeChecked();
 await expect(box.getByRole('combobox',{name:'Gemeinsame Choreografie',exact:true})).toHaveValue('unison');
 await box.getByRole('button',{name:'Trio-Einrichtung zurücknehmen',exact:true}).click();
 await expect.poll(()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)).avatarModelId,PREFS)).toBe(before.avatarModelId);
 await expect(box.getByLabel('Musiksteuerung für Sonic Stage Crew',{exact:true})).not.toBeChecked();
 await expect(box.getByLabel('Eigene Reaktionen der Figuren',{exact:true})).not.toBeChecked();
 await expect(box.getByRole('combobox',{name:'Gemeinsame Choreografie',exact:true})).toHaveValue('canon');
 expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).enabled,GROUP)).toBe(false);
 expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).visualizerMode,PREFS)).toBe(before.visualizerMode);
});
