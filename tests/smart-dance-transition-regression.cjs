const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../components/visualizer/smartDanceTransition.ts'),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod={exports:{}}; new Function('module','exports',js)(mod,mod.exports);
const {planDanceTransition,matchedClipTime}=mod.exports;
const base={baseSeconds:0.5,bpm:120,genre:'Deutschrap',outgoingTime:2,outgoingDuration:4,incomingDuration:8,grounded:true};
const a=planDanceTransition(base);
assert(a.duration>=0.08 && a.duration<=1.5);
assert(a.preservePhase);
assert.equal(matchedClipTime(a,8),4);
assert(!planDanceTransition({...base,grounded:false}).preservePhase);
assert(!planDanceTransition({...base,sameClip:true}).preservePhase);
assert(!planDanceTransition({...base,incomingDuration:0}).preservePhase);
assert(planDanceTransition({...base,genre:'Hardtekk'}).duration<a.duration);
assert(Number.isFinite(planDanceTransition({...base,bpm:NaN,baseSeconds:Infinity}).duration));
assert.equal(matchedClipTime(a,NaN),0);
console.log('Smart dance transitions: 8 regression checks passed');
