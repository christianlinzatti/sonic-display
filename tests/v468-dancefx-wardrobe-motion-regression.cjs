'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {load}=require('./helpers/ts-loader-v404.cjs');
const {advanceDanceFxEnvelopeV468:step,initialDanceFxEnvelopeV468:init}=load('components/visualizer/danceVisualEngineV468');
const sound={bass:.86,mids:.42,highs:.6,volume:.7,beat:true,beatStrength:.9,bpm:150,kick:.95,snare:.2,hiHat:.1,energyEnvelope:.7,attack:.75,decay:.1,kickAccent:'strong',kickAccentIntensity:.9,kickAnticipation:.7};
const opts={playing:true,reducedMotion:false,strength:85,tier:'high'};
let a=step(init(),sound,1/60,opts);
assert(a.pulse>0&&a.glitch>0&&a.blur>0,'first real kick must trigger effects');
const first=a.lastKick;
for(let i=0;i<10;i++)a=step(a,sound,1/60,opts);
assert.equal(a.lastKick,first,'cooldown prevents per-frame retrigger');
assert(a.pulse<.65&&a.glitch<.23&&a.blur<.4,'effects bounded');
a=step(a,{...sound,beat:false,kickAccent:'none',kickAccentIntensity:0,kick:0,beatStrength:0},.05,opts);
a=step(a,{...sound,beat:true},.05,opts);
assert(a.lastKick>first,'later beat edge retriggers');
assert.equal(step(a,sound,.02,{...opts,tier:'low'}).glitch,0,'low tier no glitch');
assert.equal(step(a,sound,.02,{...opts,reducedMotion:true}).pulse,0,'reduced motion no pulse');
assert.equal(step(a,sound,.02,{...opts,playing:false}).blur,0,'paused no temporal trails');
const long=Array.from({length:6000}).reduce((state,_,i)=>step(state,{...sound,beat:i%15===0,kickAccent:'none'},.016,opts),init());
for(const n of Object.values(long))if(typeof n==='number')assert(Number.isFinite(n),'hours of visual effects stay finite');
const read=p=>fs.readFileSync(p,'utf8');
const scene=read('components/visualizer/ThreeAvatar.tsx');
const fx=read('components/visualizer/DancePostProcessingV468.tsx');
const shader=read('components/visualizer/ProceduralShaderEnvironmentV468.tsx');
const wardrobe=read('components/visualizer/avatarWardrobeV468.ts');
const motion=read('hooks/useAudioMotionEngine.ts');
const stage=read('components/visualizer/VisualizerStage.tsx');
const ui=read('components/SettingsPanel.tsx');
const prefs=read('context/UiPreferencesContext.tsx');
assert(scene.includes('<DancePostProcessingV468')&&scene.includes('<ProceduralShaderEnvironmentV468')&&scene.includes('musicMotionV468.bindBones(model)'));
assert(scene.includes('prepareAvatarWardrobeV468(model)')&&scene.includes('wardrobeV468.dispose()'));
assert(stage.includes('wardrobeModeV468={preferences.wardrobeModeV468')&&stage.includes('audioMotionEnabledV468={preferences.audioMotionEnabledV468'));
assert(ui.includes('Visual Performance · V468')&&ui.includes('Cyberpunk-Tunnel')&&ui.includes('Avatar-Kleidung'));
assert(prefs.includes('shaderEnvironmentV468: \'auto\'')&&prefs.includes('wardrobeModeV468: \'album\''));
assert(fx.includes('AfterimagePass')&&fx.includes('OutputPass')&&fx.includes('getActivePerformanceTier()')&&fx.includes('reducedMotion'));
assert(shader.includes('getActivePerformanceTier()')&&shader.includes('galaxy')&&shader.includes('tunnel'));
assert(wardrobe.includes('original.clone()')&&wardrobe.includes('isClothingMaterialV468')&&wardrobe.includes('material.dispose()'));
assert(motion.includes('entry.before.copy(entry.bone.quaternion)')&&motion.includes('protectFootIK')&&!motion.includes('Math.random')&&!motion.includes('Date.now'));
assert(!fx.includes('window.setInterval')&&!fx.includes('requestAnimationFrame'));
console.log('PASS V468: kick envelope, rate limiting, drop strength, reduced motion, low tier, 6000 frames, GLB material ownership and integration');
