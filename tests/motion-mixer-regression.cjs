const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const input = fs.readFileSync('components/visualizer/motionDebugControls.ts','utf8');
const js = ts.transpileModule(input,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod={exports:{}};
vm.runInNewContext(js,{exports:mod.exports,module:mod,Event:class{},window:undefined});
const {readMotionDebugSettings,setMotionDebugSettings,getRuntimeMotionSettings,filterMotionDebugLayers}=mod.exports;
const defaults=readMotionDebugSettings();
assert.equal(defaults.weights.head,1);
const sample={headNod:0.8,armSwing:0.5,torsoTwist:0.25,legGroove:0.2};
setMotionDebugSettings({...defaults, weights:{...defaults.weights,head:0.5,arms:1.5,physics:0},layers:{...defaults.layers,legs:false}});
const result=filterMotionDebugLayers(sample,getRuntimeMotionSettings());
assert.equal(result.headNod,0.4);assert.equal(result.armSwing,0.75);assert.equal(result.torsoTwist,0);assert.equal(result.legGroove,0);
assert.equal(sample.headNod,0.8);
setMotionDebugSettings({...defaults,weights:{...defaults.weights,head:Infinity,arms:8}});
const safe=readMotionDebugSettings();assert.equal(safe.weights.head,1);assert.equal(safe.weights.arms,1.5);
console.log('PASS motion layer mixer: gains, isolation, safety, non-mutation');
