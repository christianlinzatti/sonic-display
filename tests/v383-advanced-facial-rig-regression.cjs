const cache=new Map();
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
function load(file){
 const full=path.resolve(root,file);
 if(cache.has(full))return cache.get(full).exports;
 const compiled=ts.transpileModule(read(file),{fileName:full,reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
 assert.equal(compiled.diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length??0,0,file);
 const mod=new Module(full,module);mod.filename=full;mod.paths=Module._nodeModulePaths(path.dirname(full));cache.set(full,mod);
 const native=mod.require.bind(mod);
 mod.require=name=>name.startsWith('./')?load(path.join(path.relative(root,path.dirname(full)),name+'.ts')):native(name);
 mod._compile(compiled.outputText,full);return mod.exports;
}
