'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {load}=require('./helpers/ts-loader-v404.cjs');
const source=load('components/visualizer/vocalStemAnalysisV643');
const v=load('components/visualizer/vocalAnalysisStudioV661');
const track='v661-isolated-user-song',rate=8000,durationMs=8000;
const chan=Float32Array.from({length:rate*8},(_,i)=>{
 const t=i/rate;
 // Two voiced sections with several amplitude attacks and a real silent gap.
 const on=t>=.8&&t<=3.2||t>=4.5&&t<=7.2;
 const envelope=(Math.floor(t*4)%2===0?.20:.08);
 return on?Math.sin(2*Math.PI*180*t)*envelope:0;
});
const first=source.analyzeIsolatedVocalStemV643([chan],rate,track,0,durationMs);
const second=source.analyzeIsolatedVocalStemV643([chan],rate,track,2,durationMs);
assert(first&&second);
const review=v.inspectVocalStemV661(first,track,durationMs);
assert(review);
assert.equal(review.trackId,track);
assert.equal(review.slot,0);
assert(review.phrases>=2);
assert(review.pauses.some(x=>x.endMs-x.startMs>=240));
assert(review.estimatedOnsetCandidates.every(p=>p.atMs>=0&&p.atMs<durationMs&&p.energy>=0&&p.energy<=1&&p.onset>=0&&p.onset<=1));
assert(review.estimatedOnsetCandidates.every((p,i,a)=>i===0||p.atMs-a[i-1].atMs>=160));
assert.equal(v.inspectVocalStemV661(first,'other',durationMs),null);
assert.equal(v.inspectVocalStemV661(first,track,20000),null);
assert.equal(v.inspectVocalStemV661({...first,source:'not-isolated'},track,durationMs),null);
assert.equal(v.setLiveVocalEnvelopeV661([first,first],track,durationMs),false);
assert.equal(v.setLiveVocalEnvelopeV661([first,second],track,durationMs),true);
assert.deepEqual(v.getLiveVocalEnvelopeV661().slots,[0,2]);
assert.equal(v.sampleLiveVocalEnvelopeV661('other',0,1600,true),null);
assert.equal(v.sampleLiveVocalEnvelopeV661(track,1,1600,true),null);
assert.equal(v.sampleLiveVocalEnvelopeV661(track,0,1600,false),null);
assert.equal(v.sampleLiveVocalEnvelopeV661(track,0,-1,true),null);
assert.equal(v.sampleLiveVocalEnvelopeV661(track,0,durationMs,true),null);
assert.equal(v.sampleLiveVocalEnvelopeV661(track,0,4000,true),null,'real detected pause cannot drive jaw');
const active=v.sampleLiveVocalEnvelopeV661(track,0,1600,true);
assert(active&&active.energy>0);
assert.equal(v.refineVocalJawV661(.30,0,null),.30);
assert(v.refineVocalJawV661(.3,0,{energy:1,onset:1})>.3);
assert(v.refineVocalJawV661(.3,1,{energy:1,onset:1})<=.015+1e-8,'lip seal caps jaw');
assert.equal(v.refineVocalJawV661(.3,0,{energy:0,onset:0}),.3);
v.clearVocalEnvelopeOnTrackChangeV661(track);
assert(v.getLiveVocalEnvelopeV661());
v.clearVocalEnvelopeOnTrackChangeV661('next-song');
assert.equal(v.getLiveVocalEnvelopeV661(),null);
assert.equal(v.sampleLiveVocalEnvelopeV661(track,0,1600,true),null);
assert.equal(v.setLiveVocalEnvelopeV661([first],track,durationMs),true);
v.clearLiveVocalEnvelopeV661();
assert.equal(v.getLiveVocalEnvelopeV661(),null);
const panel=fs.readFileSync('components/visualizer/VocalStemLabV643.tsx','utf8');
const rig=fs.readFileSync('components/visualizer/VocalRigV368.tsx','utf8');
const shell=fs.readFileSync('components/SmartLazySettings.tsx','utf8');
assert(panel.includes('V661 · Vocal Analysis Studio')&&panel.includes('setLiveVocalEnvelopeV661'));
assert(panel.includes('clearLiveVocalEnvelopeV661()')&&panel.includes('useMemo(()=>stems.map'));
assert(rig.includes('sampleLiveVocalEnvelopeV661')&&rig.includes('coordinated?.confidence===\'word\'')&&rig.includes('refineVocalJawV661'));
assert(rig.includes('manualVisemeV644')&&rig.includes('!authoredPriorityV499'));
assert(shell.includes('clearVocalEnvelopeOnTrackChangeV661(trackId)'));
console.log('PASS V661: local stem-derived pulse/pause review, opt-in/slot/track guards, mouth priority, cleanup');
