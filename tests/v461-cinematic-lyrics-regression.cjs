'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {load}=require('./helpers/ts-loader-v404.cjs');
const {planCinematicLyricsV461:plan}=load('components/visualizer/cinematicLyricsV461');
const base={line:{startMs:1000,endMs:3800,text:'Eins zwei drei vier fünf'},
  synchronized:true,playing:true,reducedMotion:false,layout:'standard',userScale:1};
const regular=plan(base);
assert.equal(regular.density,'normal');assert.equal(regular.visibleLineCount,3);
assert.equal(regular.fontScale,1);assert(regular.motionScale>0);
const long={...base,line:{...base.line,text:Array(18).fill('Rhythmus').join(' '),endMs:4500}};
const denseStage=plan({...long,layout:'immersive'});
assert.equal(denseStage.density,'rapid');assert.equal(denseStage.visibleLineCount,1);
assert(denseStage.fontScale<1);assert(denseStage.fontScale>=.76);
assert(denseStage.motionScale<regular.motionScale);
assert.equal(denseStage.wordEntranceDelayMs,0);
assert.equal(plan(long).visibleLineCount,3,'split view retains context');
assert.equal(plan({...long,synchronized:false,layout:'immersive'}).visibleLineCount,3,'unsynced lyrics retain context');
assert.equal(plan({...base,reducedMotion:true}).motionScale,0);
assert.equal(plan({...base,playing:false}).wordEntranceDelayMs,0);
const timed={...base,line:{...base.line,words:[{text:'Eins',startMs:1000,endMs:1500},{text:'zwei',startMs:1600,endMs:1800}]}};
assert.equal(plan(timed).realWordTiming,true);
assert.equal(plan({...timed,line:{...timed.line,words:[{text:'Eins',startMs:2500},{text:'zwei',startMs:1200}]}}).realWordTiming,false);
const huge={...base,line:{...base.line,text:'EinSehrSehrSehrSehrSehrSehrLangesWort'}};
assert.equal(plan({...huge,layout:'stage-3d'}).allowWordMeshes,false);
assert.equal(plan(base).max3DWidth,2.3);
for(let i=0;i<2000;i++){
 const line={text:Array(i%44+1).fill('Wort').join(' '),startMs:1000,endMs:1000+(i%100+1)*100};
 const out=plan({...base,line,layout:i%3===0?'stage-3d':'immersive'});
 assert(Number.isFinite(out.motionScale)&&out.motionScale>=0&&out.motionScale<=1);
 assert(Number.isFinite(out.fontScale)&&out.fontScale>=.76&&out.fontScale<=1);
 assert([1,3].includes(out.visibleLineCount));
}
const karaoke=fs.readFileSync('components/KineticLyrics.tsx','utf8');
const scene=fs.readFileSync('components/visualizer/Lyrics3DScene.tsx','utf8');
const stage=fs.readFileSync('components/visualizer/VisualizerStage.tsx','utf8');
const css=fs.readFileSync('app/globals.css','utf8');
assert(karaoke.includes('planCinematicLyricsV461('));
assert(karaoke.includes('v461.motionScale')&&karaoke.includes('v461.fontScale'));
assert(karaoke.includes('windowSize === 1 ? 0'));
assert(karaoke.includes('"--word-fill"')&&karaoke.includes('progressMs'));
assert(scene.includes('planCinematicLyricsV461('));
assert(scene.includes('maxWidth={visualV477.max3DWidth}'), 'V477 must preserve or tighten the V461 caption width');
assert(scene.includes('visualV461.allowWordMeshes'));
assert(scene.includes('activeCaptionV461?.visibleLineCount === 1'));
assert(karaoke.includes('const wordTimed = v477.timingMode === "verified-word";'), 'word karaoke requires verified timings');
assert(karaoke.includes('activePlanV477?.timingMode === "verified-word"'));  
assert(stage.includes('immersive/></div>')&&stage.includes('v461-immersive-overlay'), 'immersive display remains wired');
assert(css.includes('immersive-lyrics-overlay.v461-immersive-overlay'));
assert(css.includes('prefers-reduced-motion:reduce'));
assert(Number(require('../package.json').version.match(/v(\d+)$/)?.[1])>=461);
console.log('PASS V461: lyric density, stage-safe typography, real word timing, reduced motion, 3D fallback, immutable performance controls, integration');
