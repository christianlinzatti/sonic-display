'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {load}=require('./helpers/ts-loader-v404.cjs');
const p=load('services/monitoring/piSessionStabilityV463');
const input=(at,patch={})=>({at,trackId:'spotify-song-a',playing:true,visible:true,graphicsReady:true,...patch});
let s=p.initialPiSessionGuardV463;
s=p.advancePiSessionGuardV463(s,input(1000));
assert.equal(s.reason,'Songwechsel / GLB-Ladephase');
assert.equal(s.holdUntil,13000);
assert(p.blockAutomaticQualityV463(s,5000));
assert(!p.acceptPiSessionMetricsV463(s,5000,4900));
assert(!p.blockAutomaticQualityV463(s,13000));
assert(p.acceptPiSessionMetricsV463(s,13500,13200));
assert(!p.acceptPiSessionMetricsV463(s,13500,1300),'old frames must not count');
assert(!p.acceptPiSessionMetricsV463(s,13500,14000),'future frames must not count');
assert(!p.acceptPiSessionMetricsV463(s,13500,9500),'stale frames must not count');
const steady=p.advancePiSessionGuardV463(s,input(18000));
assert.equal(steady.holdUntil,13000,'ordinary playback must not rearm grace');
assert.equal(steady.transitions,s.transitions,'repeated samples must not create events');
s=p.advancePiSessionGuardV463(steady,input(21000,{trackId:'spotify-song-b'}));
assert.equal(s.holdUntil,33000,'song change gets a short loading grace');
assert.equal(s.trackId,'spotify-song-b');
assert(!p.acceptPiSessionMetricsV463(s,35000,20000),'old song metrics must not be reused');
s=p.advancePiSessionGuardV463(s,input(23000,{trackId:'spotify-song-b',playing:false}));
assert.equal(s.suspended,true);assert.equal(s.reason,'Wiedergabe pausiert');
s=p.advancePiSessionGuardV463(s,input(24000,{trackId:'spotify-song-b',playing:true}));
assert.equal(s.holdUntil,33000,'resume must not shorten an existing 12s track-change grace');
// A pause/resume near the end of a longer prior grace still protects the next 8 seconds.
s=p.advancePiSessionGuardV463(s,input(28000,{trackId:'spotify-song-b',visible:false}));
assert(s.suspended);
s=p.advancePiSessionGuardV463(s,input(30000,{trackId:'spotify-song-b',visible:true}));
assert.equal(s.holdUntil,38000);assert.equal(s.reason,'Tab wieder sichtbar');
s=p.advancePiSessionGuardV463(s,input(39000,{trackId:'spotify-song-b',graphicsReady:false}));
assert(s.suspended);
s=p.advancePiSessionGuardV463(s,input(40000,{trackId:'spotify-song-b',graphicsReady:true}));
assert.equal(s.holdUntil,55000,'context restore receives 15s');
s=p.advancePiSessionGuardV463(s,input(56000,{trackId:''}));assert(s.suspended);
s=p.advancePiSessionGuardV463(s,input(60000,{trackId:'spotify-song-c'}));
assert.equal(s.holdUntil,72000,'new song after inactivity');
assert(p.acceptPiSessionMetricsV463(s,73000,72990));
assert.deepEqual(p.advancePiSessionGuardV463(s,input(NaN)),s,'invalid clock no change');
assert.deepEqual(p.advancePiSessionGuardV463(s,input(-1)),s,'negative clock no change');
const jump=p.advancePiSessionGuardV463(s,input(180000,{trackId:'spotify-song-c'}));
assert.equal(jump.holdUntil,188000,'suspended computer cannot leave the guard stale');
assert.equal(p.initialPiSessionGuardV463.suspended,false,'if controller is absent, preserve old behavior');
// Exercise deterministic >30 minute playback with four avatars (pure policy, NOT a WebGL benchmark).
let run=p.initialPiSessionGuardV463,accepted=0,guarded=0;
for(let ms=5000;ms<=30*60*1000;ms+=5000){
 const songIndex=Math.floor((ms-5000)/(3*60*1000));
 run=p.advancePiSessionGuardV463(run,input(ms,{trackId:`song-${songIndex}`}));
 if(p.acceptPiSessionMetricsV463(run,ms,ms-100))accepted++;else guarded++;
 assert(Number.isFinite(run.holdUntil)&&Number.isFinite(run.lastTransitionAt));
 assert(run.transitions<=11);
}
assert(accepted>260&&guarded>=20,'30 min guard should spend most time on real measurements');
// Runtime state is shared with the original useFrame() path; no new render loop.
p.resetPiSessionGuardV463();
p.observePiSessionV463(input(1000));
assert(p.isPiQualityTransitionV463(11000));assert(!p.isPiQualityTransitionV463(15000));
p.resetPiSessionGuardV463();assert(!p.isPiQualityTransitionV463(15000));
