const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync('components/visualizer/motionDebugControls.ts','utf8');
const js = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod={exports:{}};
vm.runInNewContext(js,{exports:mod.exports,module:mod,Event:class{},window:undefined});
const {readMotionDebugSettings,setMotionDebugSettings,filterMotionDebugLayers}=mod.exports;
const assert=require('node:assert/strict');
const first=readMotionDebugSettings();
assert.equal(first.layers.physics,true);
setMotionDebugSettings({...first,layers:{...first.layers,arms:false,physics:false}});
const motion={armSwing:0.7,followThrough:0.2,torsoTwist:0.4,headNod:0.5,legGroove:0.3};
const filtered=filterMotionDebugLayers(motion,readMotionDebugSettings());
assert.equal(filtered.armSwing,0);
assert.equal(filtered.followThrough,0);
assert.equal(filtered.torsoTwist,0);
assert.equal(filtered.headNod,0.5);
assert.equal(filtered.legGroove,0.3);
assert.equal(motion.armSwing,0.7);
console.log('PASS motion debugger layer isolation and no mutation');
