'use strict';
/** Captures the actual Spotify VisualizerStage on the local Sonic Display UI using Chromium CDP.
 * Opt-in only; no synthetic track/lyrics/GLBs or fabricated FPS; no credential extraction.
 */
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {spawn}=require('node:child_process');const {setTimeout:delay}=require('node:timers/promises');
const {safeOrigin}=require('./v590-real-concert-visual-benchmark.cjs');
const {analyzePngs,contentCoverage}=require('./v590-visual-image.cjs');
const {summarizeFrames}=require('./v580-benchmark-metrics.cjs');
const {renderV592Report}=require('./v592-live-stage-report.cjs');
const {generate:generateV593Advice}=require('./v593-concert-quality-cli.cjs');
const argv=process.argv.slice(2),opt=(key,def)=>argv.find(x=>x.startsWith(`--${key}=`))?.slice(key.length+3)??def;
const origin=opt('url','http://127.0.0.1:3000'),port=Number(opt('debug-port','0'));
const seconds=Number(opt('seconds','15')),minGlb=Number(opt('min-glb','1'));
const width=Number(opt('width','1280')),height=Number(opt('height','800'));
const out=path.resolve(opt('out','artifacts/v592/live'));
const headed=argv.includes('--headed'),chromium=opt('chromium',process.env.CHROMIUM_PATH||'chromium');
const report={format:'sonic-v592-live-concert-review',status:'blocked',mode:port?'existing-local-chromium':headed?'headed-local-chromium':'headless-local-chromium',
 capturedAt:new Date().toISOString(),source:'actual-spotify-visualizer-stage',url:origin,minGlb,screen:{width,height},screenshots:[],transitions:[],warnings:[],
 limitations:['Requires a locally authenticated Sonic Display tab and Spotify playback with an actual GLB Avatar.',
  'No browser scene or GLB is generated by the benchmark.',
  'Pixel delta, NDC bounds and DOM lyrics are heuristics; human review required.',
  'rAF intervals do not measure GPU timings, thermals or Raspberry Pi performance.']};
function optionsValid(){return safeOrigin(origin)&&Number.isInteger(port)&&port>=0&&port<=65535&&
 Number.isInteger(seconds)&&seconds>=5&&seconds<=180&&Number.isInteger(minGlb)&&minGlb>=1&&minGlb<=4&&
 Number.isInteger(width)&&width>=640&&width<=3840&&Number.isInteger(height)&&height>=480&&height<=2160;}
async function main(){let child,dir,ws;const pending=new Map();let id=0;
 try{
  if(!optionsValid())throw Error('Only loopback origin, 5..180 seconds, 1..4 GLBs and safe display dimensions allowed');
  if(!globalThis.WebSocket)throw Error('Node 22+ WebSocket required');
  // Explicit --debug-port attaches to an already authenticated LOCAL Chromium tab.
  // A fresh isolated browser deliberately does NOT copy Spotify cookies or credentials.
  let debugPort=port;
  if(!debugPort){
   dir=fs.mkdtempSync(path.join(os.tmpdir(),'sonic-v592-'));
   child=spawn(chromium,[...(headed?[]:['--headless=new']),'--no-sandbox','--disable-dev-shm-usage','--no-first-run',
    '--disable-background-timer-throttling','--disable-renderer-backgrounding','--remote-debugging-port=0',`--user-data-dir=${dir}`,'about:blank'],{stdio:'ignore'});
   child.on('error',()=>{});
   for(let i=0;i<120;i++){const file=path.join(dir,'DevToolsActivePort');if(fs.existsSync(file)){
    debugPort=Number(fs.readFileSync(file,'utf8').split('\n')[0]);if(debugPort)break;}await delay(100);}
   if(!debugPort)throw Error('Local Chromium unavailable');
  }
  const tabs=await(await fetch(`http://127.0.0.1:${debugPort}/json`,{signal:AbortSignal.timeout(10000)})).json();
  const cleanOrigin=new URL(origin).origin;
  const tab=port?tabs.find(t=>t.type==='page'&&t.webSocketDebuggerUrl&&(()=>{try{return new URL(t.url).origin===cleanOrigin;}catch{return false;}})())
   :tabs.find(t=>t.type==='page'&&t.webSocketDebuggerUrl);
  if(!tab)throw Error('No local Sonic Display tab at expected loopback origin; start it and enable Chromium remote debugging');
  ws=new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise((resolve,reject)=>{ws.addEventListener('open',resolve,{once:true});ws.addEventListener('error',reject,{once:true});});
  ws.addEventListener('message',event=>{try{const m=JSON.parse(event.data),p=pending.get(m.id);if(!p)return;
   pending.delete(m.id);clearTimeout(p.timer);m.error?p.reject(Error(JSON.stringify(m.error))):p.resolve(m.result);}catch{}});
  const send=(method,params={},timeout=30000)=>new Promise((resolve,reject)=>{const n=++id,timer=setTimeout(()=>{pending.delete(n);reject(Error(`${method} timeout`));},timeout);
   pending.set(n,{resolve,reject,timer});ws.send(JSON.stringify({id:n,method,params}));});
  const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true},(seconds+45)*1000);
   if(r.exceptionDetails)throw Error(r.exceptionDetails.text||'Browser evaluation failed');return r.result?.value;};
  await send('Page.enable');await send('Runtime.enable');
  await send('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:false});
  await send('Page.navigate',{url:`${origin}/?benchmarkV592=1`});
  let stage=null;
  // Real Spotify authorization is never bypassed. On a fresh browser this times out and reports blocked.
  for(let i=0;i<120;i++){
   stage=await evaluate('window.__sonicV592?.state?.() ?? null');
   if(stage?.status==='ready'&&stage.canvas?.actors?.filter(a=>a.meshes>0&&a.bounds).length>=minGlb&&stage.stageRect)break;
   await delay(200);
  }
  if(!stage||stage.status!=='ready'||!stage.stageRect||stage.canvas.actors.filter(a=>a.meshes>0&&a.bounds).length<minGlb)
   throw Error(`Live Spotify stage not ready (${stage?.status??'missing'}); use a locally authenticated browser with playback, synced lyrics and ${minGlb} real GLB performer(s)`);
  const trackId=stage.trackId;
  if(!trackId||!stage.canvas.webglVersion)throw Error('Missing actual WebGL/track evidence');
  report.browser={userAgent:await evaluate('navigator.userAgent'),webglVersion:stage.canvas.webglVersion};
  report.sourceTrack=trackId;report.modelCount=stage.canvas.actors.length;
  // V603: actual Spotify track metadata, not estimated from the capture window.
  report.trackDurationMs=Number.isInteger(stage.durationMs)&&stage.durationMs>=1000?stage.durationMs:null;
  fs.mkdirSync(out,{recursive:true});
  let prev=null,prevId=null,initialProgress=stage.progressMs;
  const shots=Math.max(2,Math.min(8,Math.floor(seconds/2)));
  const capture=async(index)=>{
   const s=await evaluate('window.__sonicV592?.state?.() ?? null');
   if(!s||s.status!=='ready'||s.trackId!==trackId||!s.canvas||s.canvas.actors.filter(a=>a.meshes>0&&a.bounds).length<minGlb)
    throw Error(`Playback/canvas changed during real capture: ${s?.status||'missing'}`);
   const shotBytes=Buffer.from((await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false})).data,'base64');
   // Capture the real stage's authoritatively rendered show labels. Missing or ambiguous
   // labels remain unclassified; V595 never guesses performer roles or beat sections.
   const sceneEvidence=await evaluate(`(()=>{const el=document.querySelector('[data-v592-live-stage]');if(!el)return null;
    const d=el.dataset;return {moment:d.v456Moment||'',act:d.v464Act||'',shot:d.v478Shot||'',
     mode:d.v568Mode||'',focus:d.v568Focus||'',genre:d.v502Genre||''};})()`);
   const coverage=contentCoverage(shotBytes),file=`live-${String(index).padStart(2,'0')}.png`;
   fs.writeFileSync(path.join(out,file),shotBytes);
   const warnings=[...s.warnings];if(coverage.nonBackgroundFraction<.01)warnings.push('Screenshot mostly uniform');
   report.screenshots.push({file,progressMs:s.progressMs,activeIndex:s.activeIndex,actors:s.canvas.actors.length,
    drawCalls:s.canvas.drawCalls,triangles:s.canvas.triangles,lyricsMode:s.lyricsMode,coverage,warnings,
    actorBounds:s.canvas.actors.map(a=>({meshes:a.meshes,bounds:a.bounds})),stageRect:s.stageRect,lyricRect:s.lyricRect,
    sceneEvidence,lyricsPresent:s.lyricsPresent,lyricsSynced:s.lyricsSynced});
   warnings.forEach(w=>report.warnings.push(`Foto ${index}: ${w}`));
   if(prev){const change=analyzePngs(prev,shotBytes);report.transitions.push({from:prevId,to:file,...change});
    if(change.changedPixelFraction<.003)report.warnings.push(`${file}: almost identical frames; inspect playback.`);}
   prev=shotBytes;prevId=file;return {trackId:s.trackId,progressMs:s.progressMs,timestamp:Date.now()};
  };
  const progressSamples=[await capture(0)];
  const observationPromise=evaluate(`new Promise(resolve=>{const samples=[],longTasks=[];let previous=0,loss=0;const c=document.querySelector('[data-v592-live-stage] canvas');
   const onLost=()=>loss++;c?.addEventListener('webglcontextlost',onLost);let observer;
   try{observer=new PerformanceObserver(list=>{for(const x of list.getEntries())longTasks.push(x.duration)});observer.observe({entryTypes:['longtask']});}catch{}
   const start=performance.now(),end=start+${seconds*1000};function tick(now){if(previous&&now>previous)samples.push(now-previous);previous=now;
    if(now<end){requestAnimationFrame(tick);return;}observer?.disconnect();c?.removeEventListener('webglcontextlost',onLost);
    resolve({samples,elapsedMs:performance.now()-start,longTaskCount:longTasks.length,contextLosses:loss,hidden:document.hidden});}
   requestAnimationFrame(tick);})`);
  for(let i=1;i<shots;i++){
   await delay(Math.ceil(seconds*1000/(shots-1)));
   progressSamples.push(await capture(i));
  }
  const frames=await observationPromise;
  const metrics=summarizeFrames(frames.samples,{targetFps:30});
  if(metrics.status!=='measured'||frames.hidden||frames.contextLosses)throw Error('No stable browser frames measured');
  // Snapshots are taken from the live stage after timing, at ACTUAL progressive song times.
  // No deliberate media seek or injected show cue is used.
  const after=progressSamples[progressSamples.length-1];
  if(after.progressMs-initialProgress<Math.max(1300,seconds*650)||
    progressSamples.some((sample,i)=>i>0&&sample.progressMs<=progressSamples[i-1].progressMs+250))
    throw Error('Song did not progress consistently during actual observations; playback seek/pause suspected');
  if(report.screenshots.length<2)throw Error('Not enough real captures');
  report.frameTiming={...metrics,elapsedMs:frames.elapsedMs,longTaskCount:frames.longTaskCount,contextLosses:frames.contextLosses};
  report.progressMs=after.progressMs-initialProgress;
  report.status='measured-needs-human-review';
  fs.writeFileSync(path.join(out,'report.html'),renderV592Report(report));
  try{generateV593Advice(report,out);}catch(advisorError){
   report.warnings.push(`V593 advisory unavailable: ${String(advisorError?.message||advisorError)}`);
   console.warn('V593 advisory unavailable; V592 measurements remain valid.');
  }
  console.log(`V592 LIVE: ${report.screenshots.length} real VisualizerStage captures; ${metrics.averageFps} rAF/s. Human review required.`);
 }catch(error){report.error=String(error?.message||error);console.error('V592 BLOCKED:',report.error);}
 finally{fs.mkdirSync(out,{recursive:true});fs.writeFileSync(path.join(out,'report.json'),JSON.stringify(report,null,2)+'\n');
  if(ws)try{ws.close();}catch{}for(const p of pending.values())clearTimeout(p.timer);
  if(child)child.kill('SIGKILL');if(dir)try{fs.rmSync(dir,{recursive:true,force:true});}catch{}
 }
 if(report.status!=='measured-needs-human-review')process.exitCode=1;
}
if(require.main===module)main().catch(err=>{console.error(err);process.exitCode=1;});
module.exports={optionsValid};
